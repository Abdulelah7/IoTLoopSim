"""Generate scalability scenarios: N Wi-Fi devices, one gateway + one edge node per 250 devices."""
import sys, math, pathlib
out = pathlib.Path(sys.argv[1]); out.mkdir(parents=True, exist_ok=True)
for n in [int(x) for x in sys.argv[2:]]:
    c = max(1, math.ceil(n / 250))
    y = f"""# Scalability benchmark (generated by gen_scal.py): {n} devices, {c} cells
name: scal-{n}
seed: 1
duration: 10min
deviceStart: 10s
fidelity: {{links: queue, radio: queue}}
policies: {{placement: edge-first, selector: nearest-least-loaded}}
gateways:
  - {{name: gw, count: {c}, techs: [wifi], grid: {{x0: 0, y0: 0, dx: 300}}}}
nodes:
  - {{name: edge, count: {c}, tier: edge, cores: 4, mips: 2000, ram: 8192, grid: {{x0: 0, y0: 0, dx: 300}}}}
  - {{name: cloud, tier: cloud, cores: 64, mips: 4000, ram: 262144, registry: true}}
links:
  - {{between: [gw-*, edge-*], bandwidth: 1Gbps, latency: 1ms}}
  - {{between: [edge-*, cloud], bandwidth: 1Gbps, latency: 20ms}}
devices:
  - group: room
    count: {n}
    tech: wifi
    protocol: mqtt-qos1
    nearGateways: 100
    sensors:
      - {{type: temp, interval: exp(5), bytes: 32, energy: 0.001}}
    actuators:
      - {{type: valve, time: const(20), energy: 0.05}}
applications:
  - name: hvac
    trigger: temp
    actuator: valve
    deadline: 200ms
    modules:
      - {{name: control, mi: 50, out: 64, cores: 4, min: {c}, max: {c}, image: {{name: "ctl:1", size: 80MB}}, startup: const(1), actuate: true}}
"""
    (out / f"scal-{n}.yaml").write_text(y)
